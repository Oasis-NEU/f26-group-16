// Writes docs/category_pictures.sql: one UPDATE per category that sets
// event_categories.picture_data to the matching WebP in scripts/category_images
// (named <category_id>.webp; credits in CREDITS.md there).
//
//   node scripts/category_pictures_sql.mjs
//
// Only admins can write event_categories, so run the output in the Supabase SQL
// editor (after docs/migrations/2026-11-19_all_day_archive_category_pictures.sql).

import { readdir, readFile, writeFile } from 'node:fs/promises'

const IMAGES = new URL('./category_images/', import.meta.url)
const OUTPUT = new URL('../docs/category_pictures.sql', import.meta.url)
// Same limit as the CHECK rule: 10 MiB of picture data.
const MAX_BYTES = 10 * 1024 * 1024

const files = (await readdir(IMAGES)).filter((name) => name.endsWith('.webp')).sort()
if (files.length === 0) {
  console.error('No .webp files in scripts/category_images.')
  process.exit(1)
}

const lines = [
  '-- Default cover pictures for event categories (event_categories.picture_data).',
  '-- Generated by scripts/category_pictures_sql.mjs from scripts/category_images',
  '-- (credits in scripts/category_images/CREDITS.md). Run in the Supabase SQL editor',
  '-- after docs/migrations/2026-11-19_all_day_archive_category_pictures.sql.',
  '',
]
for (const name of files) {
  const categoryId = name.replace(/\.webp$/, '')
  const bytes = await readFile(new URL(name, IMAGES))
  if (bytes.length > MAX_BYTES) throw new Error(`${name} is over 10MB.`)
  if (bytes.subarray(0, 4).toString() !== 'RIFF' || bytes.subarray(8, 12).toString() !== 'WEBP') {
    throw new Error(`${name} isn't a WebP file.`)
  }
  const dataUrl = `data:image/webp;base64,${bytes.toString('base64')}`
  lines.push(`UPDATE event_categories SET picture_data = '${dataUrl}' WHERE category_id = '${categoryId}';`)
  console.log(`${categoryId}: ${Math.round(bytes.length / 1024)} KB`)
}
lines.push('')
await writeFile(OUTPUT, lines.join('\n'))
console.log(`\nWrote docs/category_pictures.sql (${files.length} categories).`)
